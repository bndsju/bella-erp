-- Permissoes por perfil: uma linha por (perfil, modulo, acao) concedida. O ADMINISTRADOR nao aparece:
-- ele sempre tem acesso total e isso nao e configuravel. Os valores iniciais reproduzem as regras que existiam
-- fixas no codigo (ver PermissoesPadrao).
CREATE TABLE bella.permissoes_perfil (
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('GERENTE', 'FINANCEIRO', 'VENDEDOR')),
    modulo VARCHAR(30) NOT NULL,
    acao   VARCHAR(10) NOT NULL CHECK (acao IN ('VER', 'CRIAR', 'EDITAR', 'CANCELAR')),
    PRIMARY KEY (perfil, modulo, acao)
);

